#!/usr/bin/env bash
# stranger-walkthrough.sh — run the install guide's first ten minutes against a
# released binary set and print the transcript as AsciiDoc console blocks with
# timings, so the quickstart page is regenerated rather than recalled.
#
#   tools/stranger-walkthrough.sh --version 2.8.59 [--keep]
#
# What it measures, in an empty HOME (a machine that has never had tebako):
#   setup · install a toolkit payload · install-shell · run it by name ·
#   install a runtime-carrying payload · first run (the runtime download) ·
#   press a one-file app twice (cold, then the iteration loop)
#
# It never touches the caller's store: HOME and TEBAKO_HOME both point into a
# scratch directory, which is removed unless --keep is passed. The script is
# the page's provenance: every number the page prints comes from one run of
# this script, and the version it ran against is printed in the header.
set -euo pipefail

VERSION=""
PLATFORM=""
KEEP=0
while [ $# -gt 0 ]; do
  case "$1" in
    --version) VERSION="${2:?--version takes X.Y.Z}"; shift 2 ;;
    --platform) PLATFORM="${2:?}"; shift 2 ;;
    --keep) KEEP=1; shift ;;
    *) echo "usage: $0 --version X.Y.Z [--platform macos-arm64] [--keep]" >&2; exit 64 ;;
  esac
done
[ -n "$VERSION" ] || { echo "--version is required" >&2; exit 64; }
if [ -z "$PLATFORM" ]; then
  case "$(uname -s)-$(uname -m)" in
    Darwin-arm64) PLATFORM="macos-arm64" ;;
    Darwin-x86_64) PLATFORM="macos-x86_64" ;;
    Linux-x86_64) PLATFORM="linux-gnu-x86_64" ;;
    Linux-aarch64) PLATFORM="linux-gnu-arm64" ;;
    *) echo "unknown host; pass --platform" >&2; exit 64 ;;
  esac
fi

BASE="https://github.com/tamatebako/tebako/releases/download/v${VERSION}"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/tebako-stranger-XXXXXX")"
# Resolve once: macOS's TMPDIR carries a doubled slash and a /private prefix,
# so a path compared against the tool's output would never match.
WORK="$(cd "$WORK" && pwd -P)"
cleanup() { [ "$KEEP" -eq 1 ] || rm -rf "$WORK"; }
trap cleanup EXIT

BIN="$WORK/bin"
HOME_DIR="$WORK/home"
mkdir -p "$BIN" "$HOME_DIR"
export HOME="$HOME_DIR"
export TEBAKO_HOME="$HOME_DIR/.tebako"
export PATH="$BIN:$PATH"

# The release asset names carry the version; the binaries expect the bare
# names. This rename is the step the guide used to omit, and forgetting it
# stops the install at the shim step after the payload has downloaded.
fetch() {
  local name="$1"
  curl -fsSL -o "$BIN/$name" "$BASE/$name-${VERSION}-${PLATFORM}"
  chmod 0755 "$BIN/$name"
}
for b in tebako tebako-pkg tfs tebako-bootstrap tebako-shim; do fetch "$b"; done

# centiseconds, so a 0.15 s step is not reported as 0 s.
now() { perl -MTime::HiRes=time -e 'printf "%.2f", time'; }
declare -a NAMES TIMES CODES
mkdir -p "$WORK/logs"
# One slug function for both the writer and the reader: BSD sed has no BRE
# alternation, so the trim is parameter expansion.
slugof() {
  local s
  s=$(printf '%s' "$1" | tr -cs 'a-z0-9' '-')
  s="${s#-}"; s="${s%-}"
  printf '%s' "$s"
}
step() {
  local name="$1"; shift
  local t0 t1 rc slug
  slug=$(slugof "$name")
  t0=$(now)
  set +e
  "$@" >"$WORK/logs/$slug.log" 2>&1
  rc=$?
  set -e
  t1=$(now)
  NAMES+=("$name")
  TIMES+=("$(printf '%.2f' "$(echo "$t1 - $t0" | bc)")")
  CODES+=("$rc")
}

echo "// Generated by tools/stranger-walkthrough.sh — tebako v${VERSION}, ${PLATFORM}"
echo "// One run, $(date -u +%Y-%m-%dT%H:%M:%SZ). Empty HOME, release assets as published."
echo

step "tebako setup" tebako setup
step "tebako install hello" tebako install hello
step "tebako-shim install-shell" tebako-shim install-shell
# install-shell writes the PATH line into the user's shell startup file, which
# a non-interactive script never reads: put the shim directory on THIS process's
# PATH so the run below is the same run the reader makes in a fresh terminal.
export PATH="$TEBAKO_HOME/shims:$PATH"
step "hello" hello

step "tebako install hello-ruby" tebako install hello-ruby
step "hello-ruby (first run)" hello-ruby

PROJ="$WORK/tinyapp"
mkdir -p "$PROJ"
printf 'puts "hello from a pressed app (ruby #{RUBY_VERSION})"\n' >"$PROJ/main.rb"
mkdir -p "$WORK/out"
pushd "$PROJ" >/dev/null
# Output OUTSIDE the project root: pressing in place is what the tool warns
# about, and the warning is noise on a page that should show the good path.
step "tebako press (cold)" tebako press -r . -e main.rb -o "$WORK/out/hello"
step "tebako press (again)" tebako press -r . -e main.rb -o "$WORK/out/hello"
step "the pressed app" "$WORK/out/hello"
popd >/dev/null

echo "[cols=\"2,1,1\",options=\"header\"]"
echo "|==="
echo "| step | seconds | exit"
for i in "${!NAMES[@]}"; do
  printf "| \`%s\` | %s | %s\n" "${NAMES[$i]}" "${TIMES[$i]}" "${CODES[$i]}"
done
echo "|==="
echo
echo "// store after the run"
# The store's size and its runtimes, not its scratch path: du canonicalises
# the path on macOS, and a reader needs the shape of what landed.
printf '// store: %s at ~/.tebako\n' "$(du -sh "$TEBAKO_HOME" 2>/dev/null | cut -f1)"
ls "$TEBAKO_HOME/runtimes" 2>/dev/null | sed 's/^/\/\/ runtime: /'
echo
# The console blocks the page shows, taken from this run. The scratch HOME is
# normalised to ~ so the reader sees the paths they will actually get.
transcript() {
  local slug; slug=$(slugof "$1")
  local skip="${2:-0}"
  echo "[source,console]"
  echo "----"
  sed -e "s|$HOME|~|g" -e "s|$WORK|\$work|g" "$WORK/logs/$slug.log" \
    | tail -n +$((skip + 1)) | sed '/^$/d'
  echo "----"
  echo
}
echo "// the transcripts this run produced"
echo
echo "=== tebako setup · install hello · install-shell · hello ==="
transcript "tebako-setup" 1
transcript "tebako-install-hello" 1
transcript "tebako-shim-install-shell"
transcript "hello"
echo "=== a payload that carries a runtime ==="
transcript "hello-ruby-first-run"
echo "=== press your own ==="
transcript "tebako-press-cold"
transcript "the-pressed-app"
